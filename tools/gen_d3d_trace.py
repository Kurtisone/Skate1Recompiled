#!/usr/bin/env python3
"""Generate src/d3d_trace.cpp: a counting hook on every function of the XDK
graphics libraries (D3D9, D3DX9, XGRAPHC) that game code calls, to map which
D3D entry points Skate 1 uses, how often, from where and in which order.

The library range is a guess (see NOTES.md); functions are taken from direct
`bl` call sites in generated/default/*.cpp whose caller is outside the range.

    tools/gen_d3d_trace.py            # writes src/d3d_trace.cpp
"""
import glob
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RANGES = [(0x82C80000, 0x82D10000), (0x82F48000, 0x82F4C000)]
SWAP = 0x82CCBE98  # D3DDevice_Swap: frame boundary
# Hooked elsewhere (src/frame_cap.cpp), which reports to the tracer itself.
HOOKED_ELSEWHERE = {SWAP}


def in_range(a):
    return any(lo <= a < hi for lo, hi in RANGES)


def main():
    targets = set()
    cur = None
    for path in glob.glob(str(ROOT / "generated/default/skate1_recomp.*.cpp")):
        for line in open(path, errors="ignore"):
            m = re.match(r"DEFINE_REX_FUNC\(sub_([0-9A-F]+)\)", line)
            if m:
                cur = int(m.group(1), 16)
                continue
            m = re.match(r"\s*// bl 0x([0-9a-f]+)", line)
            if m and cur is not None:
                t = int(m.group(1), 16)
                if in_range(t) and not in_range(cur):
                    targets.add(t)
    targets.add(SWAP)
    targets = sorted(targets)
    swap_index = targets.index(SWAP)

    out = []
    out.append("// Generated by tools/gen_d3d_trace.py - do not edit.\n")
    out.append("// Counting hooks on the XDK graphics library entry points game code calls.\n")
    out.append('#include "d3d_trace.h"\n\n#include <rex/hook.h>\n\n')
    out.append('#include "generated/default/skate1_init.h"\n\n')
    out.append(f"const uint32_t kD3DTraceAddresses[{len(targets)}] = {{\n")
    for i in range(0, len(targets), 6):
        out.append("    " + ", ".join(f"0x{a:08X}" for a in targets[i:i + 6]) + ",\n")
    out.append("};\n")
    out.append(f"const uint32_t kD3DTraceCount = {len(targets)};\n")
    out.append(f"const uint32_t kD3DTraceSwapIndex = {swap_index};\n\n")
    for i, a in enumerate(targets):
        if a in HOOKED_ELSEWHERE:
            continue
        out.append(f"REX_HOOK_RAW(sub_{a:08X}) {{\n"
                   f"  D3DTraceEnter({i}, ctx, base);\n"
                   f"  __imp__sub_{a:08X}(ctx, base);\n"
                   f"  D3DTraceLeave({i});\n"
                   f"}}\n")
    (ROOT / "src/d3d_trace.cpp").write_text("".join(out))
    print(f"{len(targets)} hooks, swap index {swap_index}", file=sys.stderr)


if __name__ == "__main__":
    main()
